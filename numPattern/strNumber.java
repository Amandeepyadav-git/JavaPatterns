package numPattern;
//right angle pattern 1 to 5 in java

public class strNumber {
    public static void main(String[] args) {
        int n =5 ;
        for(int i = 1; i<=n;i++){
            for(int j = 1;j<=i;j++){
                System.out.print(j);
            }
            System.out.println();
        }
    }

}